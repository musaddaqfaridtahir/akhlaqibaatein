export function getDuroodBySlug(slug: string): DuroodItem | undefined {
  return duroodList.find((item) => item.slug === slug);
}

export function getDuroodsByCategory(category: DuroodCategory | 'All'): DuroodItem[] {
  if (category === 'All') return duroodList;
  return duroodList.filter((item) => item.category === category);
}

export function getDuroodCategoryLabelUr(category: DuroodCategory): string {
  const found = DUROOD_CATEGORIES.find((c) => c.id === category);
  return found ? found.labelUr : category;
}
